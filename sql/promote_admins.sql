-- ============================================================================
--  الخطوة ب — الترقية (شغّل هذا دائماً)
-- ============================================================================

-- 1) ترقية المشرفين العاديين
update public.profiles p
   set is_admin = true
 where coalesce(p.is_admin, false) = false
   and public.is_admin_email(p.email);

-- 2) ترقية المشرف العام (يملك is_admin أيضاً)
update public.profiles p
   set is_admin = true,
       is_super_admin = true
 where coalesce(p.is_super_admin, false) = false
   and public.is_super_admin_email(p.email);


-- ============================================================================
--  الخطوة ج — تقرير النتيجة (المطلوب: صف واحد على الأقل بـ is_super_admin = t)
-- ============================================================================

select email,
       is_admin       as "مشرف",
       is_super_admin as "مشرف عام",
       created_at::date as "تاريخ التسجيل"
  from public.profiles
 order by is_super_admin desc, is_admin desc, email;
